"""Reviewer 1, Comment 1.17: sequential-generation generalization under disjoint splits.
Rebuilt from the manuscript: 20 antecedent-consequent activity chains x 12 entities, 160 of 240 combinations sampled;
input = the two atomic-fact embeddings [T_A, T_B] (IDF-free mean GloVe-100 of the fact sentence), output = compound
sentence "after <A-ing>, <entity> <B>" generated by a word-level encoder-decoder LSTM (teacher forcing, greedy decoding).
Splits: (1) unseen combinations (random 120/40, as in the manuscript), (2) unseen templates (same split, test facts
phrased with a disjoint template set), (3) unseen entities, (4) unseen chains, (5) reversed order (held-out pairs presented
B then A; target 'after B, e A')."""
import gzip, json, random, sys
import numpy as np, torch, torch.nn as nn

ACT = {'breakfast': ('eating breakfast', 'eats breakfast'), 'cricket': ('playing cricket', 'plays cricket'),
       'yoga': ('doing yoga', 'does yoga'), 'shower': ('taking a shower', 'takes a shower'),
       'meeting': ('attending a meeting', 'attends a meeting'), 'lunch': ('having lunch', 'has lunch'),
       'work': ('starting work', 'starts work'), 'walk': ('going for a walk', 'goes for a walk'),
       'gym': ('visiting the gym', 'visits the gym'), 'dinner': ('cooking dinner', 'cooks dinner'),
       'reading': ('reading a book', 'reads a book'), 'music': ('listening to music', 'listens to music'),
       'shopping': ('going shopping', 'goes shopping'), 'tea': ('drinking tea', 'drinks tea')}
CHAINS = [('breakfast', 'cricket'), ('yoga', 'shower'), ('meeting', 'lunch'), ('work', 'lunch'), ('gym', 'shower'),
          ('walk', 'tea'), ('cricket', 'shower'), ('shopping', 'dinner'), ('reading', 'music'), ('tea', 'reading'),
          ('work', 'meeting'), ('dinner', 'walk'), ('breakfast', 'work'), ('lunch', 'walk'), ('music', 'yoga'),
          ('shower', 'breakfast'), ('gym', 'tea'), ('meeting', 'shopping'), ('yoga', 'breakfast'), ('walk', 'dinner')]
ENT = ['neha', 'rahul', 'priya', 'amit', 'anita', 'vikram', 'sunita', 'arjun', 'kavita', 'rohan', 'meera', 'karan']
TPL = [['{e} {v}', '{e} usually {v}'], ['every day {e} {v}', '{e} regularly {v}'], ['{e} often {v}', 'most days {e} {v}']]

G = {}
with gzip.open('./glove100.gz', 'rt', encoding='utf8') as f:
    need = {w for a in ACT.values() for p in a for w in p.split()} | set(ENT) | {w for s in TPL for t in s for w in t.split()}
    for line in f:
        w, rest = line.split(' ', 1)
        if w in need: G[w] = np.array(rest.split(), dtype=np.float32)


def emb(sent):
    v = [G[w] for w in sent.split() if w in G]
    x = np.mean(v, 0); return x / np.linalg.norm(x)


def fact(e, a, tset, rng):
    return emb(rng.choice(TPL[tset]).format(e=e, v=ACT[a][1]))


PH = False
def target(e, a, b, ph=None):
    ph = PH if ph is None else ph
    return f'after {ACT[a][0]} , {"<E>" if ph else e} {ACT[b][1]}'.split()


class S2S(nn.Module):
    def __init__(self, V, H=128, E=64):
        super().__init__()
        self.enc = nn.LSTM(100, H, batch_first=True); self.emb = nn.Embedding(V, E)
        self.dec = nn.LSTM(E, H, batch_first=True); self.out = nn.Linear(H, V)

    def forward(self, x, y_in):
        _, h = self.enc(x); o, _ = self.dec(self.emb(y_in), h); return self.out(o)

    def greedy(self, x, bos, eos, L=12):
        _, h = self.enc(x); tok = torch.full((x.shape[0], 1), bos); outs = []
        for _ in range(L):
            o, h = self.dec(self.emb(tok), h); tok = self.out(o).argmax(-1); outs.append(tok)
        return torch.cat(outs, 1)


def run(cond, seed, epochs=1000, ph=False):
    global PH; PH = ph
    rng = random.Random(seed); torch.manual_seed(seed)
    combos = [(e, c) for e in ENT for c in range(20)]
    data = rng.sample(combos, 160)                                   # 160 of the 240 combinations
    if cond in ('combinations', 'templates', 'reversed order'):
        rng.shuffle(data); tr, te = data[:120], data[120:]
    elif cond == 'entities':
        test_e = set(rng.sample(ENT, 3)); tr = [d for d in data if d[0] not in test_e]; te = [d for d in data if d[0] in test_e]
    elif cond == 'chains':
        test_c = set(rng.sample(range(20), 5)); tr = [d for d in data if d[1] not in test_c]; te = [d for d in data if d[1] in test_c]
    vocab = ['<pad>', '<bos>', '<eos>'] + sorted({w for e, c in tr for w in target(e, *CHAINS[c])})
    ix = {w: i for i, w in enumerate(vocab)}
    model = S2S(len(vocab)); opt = torch.optim.Adam(model.parameters(), 1e-3); lossf = nn.CrossEntropyLoss(ignore_index=0)
    for ep in range(epochs):                                         # fresh template draw each epoch (train sets 0-1)
        X, Yi, Yo = [], [], []
        for e, c in tr:
            a, b = CHAINS[c]; ts = rng.randrange(2)
            X.append([fact(e, a, ts, rng), fact(e, b, ts, rng)]); t = [ix[w] for w in target(e, a, b)]
            Yi.append([1] + t + [0] * (11 - len(t))); Yo.append(t + [2] + [0] * (11 - len(t)))
        X = torch.tensor(np.array(X)); Yi = torch.tensor(Yi); Yo = torch.tensor(Yo)
        opt.zero_grad(); l = lossf(model(X, Yi).reshape(-1, len(vocab)), Yo.reshape(-1)); l.backward(); opt.step()
    model.eval(); res = []
    with torch.no_grad():
        for e, c in te:
            a, b = CHAINS[c]; ts = 2 if cond == 'templates' else rng.randrange(2)
            if cond == 'reversed order':
                a, b = b, a
            x = torch.tensor(np.array([[fact(e, a, ts, rng), fact(e, b, ts, rng)]]))
            out = []
            for t in model.greedy(x, 1, 2)[0].tolist():
                if t == 2: break
                out.append(vocab[t])
            if PH: out = [e if w == '<E>' else w for w in out]       # fill the entity slot from the fact's entity
            ref = target(e, a, b, False); fwd = target(e, b, a, False)
            if cond == 'reversed order' and seed == 0 and len(res) < 6: print('REV', ' '.join(out), '| ref:', ' '.join(ref))
            mask = lambda s: ['<E>' if w in ENT else w for w in s]
            ov = sum(min(out.count(w), ref.count(w)) for w in set(ref)) / len(ref)
            res.append(dict(exact=out == ref, exact_noent=mask(out) == mask(ref), overlap=ov,
                            entity_ok=e in out, order_blind=out == fwd if cond == 'reversed order' else False))
    return {k: float(np.mean([r[k] for r in res])) for k in res[0]} | dict(cond=cond, seed=seed, placeholder=ph, n_train=len(tr), n_test=len(te))


if __name__ == '__main__':
    from multiprocessing import Pool
    torch.set_num_threads(1)
    jobs = [(c, s, 1000, ph) for ph in (False, True) for c in ['combinations', 'templates', 'entities', 'chains', 'reversed order'] for s in range(5)]
    with Pool(2) as p:
        out = p.starmap(run, jobs)
    json.dump(out, open('./stage2/seqgen_results.json', 'w'), indent=1)
    import collections
    g = collections.defaultdict(list)
    for r in out: g[(r['cond'], r['placeholder'])].append(r)
    for c, v in g.items():
        print(f"{str(c):30s} n_test~{np.mean([x['n_test'] for x in v]):.0f} " + ' '.join(
            f"{k}={np.mean([x[k] for x in v]):.3f}±{np.std([x[k] for x in v]):.3f}" for k in ['exact', 'exact_noent', 'overlap', 'entity_ok', 'order_blind']))
